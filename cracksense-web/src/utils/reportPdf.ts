import { jsPDF } from 'jspdf';
import autoTable from 'jspdf-autotable';
import type { Inspection } from '../types';

export async function generateInspectionPdfReport(inspection: Inspection): Promise<void> {
  const doc = new jsPDF({
    orientation: 'portrait',
    unit: 'mm',
    format: 'a4'
  });

  const isCritical = inspection.severity === 'CRITICAL';
  const hasCoords = inspection.latitude !== null && inspection.longitude !== null;

  // Header Banner
  doc.setFillColor(isCritical ? 220 : 2, isCritical ? 38 : 132, isCritical ? 38 : 199);
  doc.rect(0, 0, 210, 28, 'F');

  doc.setTextColor(255, 255, 255);
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(16);
  doc.text('CRACKSENSE AI — STRUCTURAL INTEGRITY AUDIT DOSSIER', 14, 12);

  doc.setFont('helvetica', 'normal');
  doc.setFontSize(9);
  doc.text(
    `CONFIDENTIAL CIVIL ENGINEERING DISPATCH FILE • AUDIT ID: ${inspection.id}`,
    14,
    20
  );

  // Metadata Overview
  doc.setTextColor(15, 23, 42);
  doc.setFontSize(11);
  doc.setFont('helvetica', 'bold');
  doc.text('1. Telemetry & AI Inspection Parameters', 14, 38);

  const tableData = [
    ['Inspection ID', inspection.id],
    ['Audit Timestamp', new Date(inspection.created_at).toLocaleString()],
    ['Severity Rating', inspection.severity],
    [
      'GPS Coordinates',
      hasCoords
        ? `${inspection.latitude!.toFixed(6)}, ${inspection.longitude!.toFixed(6)} (${inspection.location_status})`
        : 'Location unavailable'
    ],
    ['Inspection Mode', inspection.mode === 'OFFLINE' ? 'Offline Emergency Sync' : 'Online Cloud Audit'],
    ['Crack Fissure Count', `${inspection.crack_count} detected fissure(s)`],
    ['Estimated Dimensions', inspection.dimensions || 'N/A'],
    ['YOLOv8 AI Confidence', `${Math.round(inspection.confidence * 100)}%`],
    ['Mandated Action', inspection.recommendation || 'Standard civil engineering monitoring']
  ];

  autoTable(doc, {
    startY: 42,
    head: [['Audit Metric', 'Recorded Field Value']],
    body: tableData,
    theme: 'grid',
    headStyles: {
      fillColor: [15, 23, 42],
      textColor: [255, 255, 255],
      fontStyle: 'bold',
      fontSize: 9
    },
    styles: {
      fontSize: 9,
      cellPadding: 3.5,
      textColor: [30, 41, 59]
    },
    columnStyles: {
      0: { fontStyle: 'bold', cellWidth: 55 }
    }
  });

  const finalY = (doc as unknown as { lastAutoTable: { finalY: number } }).lastAutoTable.finalY + 10;

  // Regulatory Disclaimer Box
  doc.setFillColor(240, 253, 244);
  doc.setDrawColor(134, 239, 172);
  doc.rect(14, finalY, 182, 28, 'FD');

  doc.setTextColor(22, 101, 52);
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(10);
  doc.text('AI-based preliminary risk assessment', 18, finalY + 7);

  doc.setFont('helvetica', 'normal');
  doc.setFontSize(8.5);
  doc.text(
    'This visual machine-learning assessment identifies preliminary crack geometry and structural defect markers.\nAutomated analysis does not certify complete building safety; official on-site civil engineering inspections remain authoritative.',
    18,
    finalY + 14
  );

  // Footer
  doc.setFontSize(8);
  doc.setTextColor(148, 163, 184);
  doc.text(
    `Generated by CrackSense AI Authority Hub • Powered by InsForge BaaS • ${new Date().toUTCString()}`,
    14,
    285
  );

  // Download PDF file
  doc.save(`CrackSense_Audit_${inspection.id.substring(0, 8)}.pdf`);
}
